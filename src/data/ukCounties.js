export function filterUkCounties(query) {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return UK_COUNTIES;

  const startsWith = UK_COUNTIES.filter((county) =>
    county.toLowerCase().startsWith(trimmed),
  );
  const contains = UK_COUNTIES.filter(
    (county) =>
      !county.toLowerCase().startsWith(trimmed) &&
      county.toLowerCase().includes(trimmed),
  );

  return [...startsWith, ...contains];
}
